// The portal's palettes (content/accents.json), written as CSS for the mock:
// one block per palette for the day, one for the night, in the mock's token
// names. Run before dev and build; the output is committed too, so a plain
// `vite` still works. The same CSS is inlined into index.html between the
// palette markers, so the opening screen already wears the chosen palette.
import { readFile, writeFile } from "node:fs/promises";

const here = new URL(".", import.meta.url);
const accents = JSON.parse(await readFile(new URL("../../content/accents.json", here), "utf8"));
const map = (t) => `--paper: ${t.paper}; --surface: ${t.surface}; --surface-2: ${t.surfaceMuted}; --ink: ${t.ink}; --ink-soft: ${t.inkSoft}; --muted: ${t.muted}; --line: ${t.border}; --line-strong: ${t.hoverBorder}; --accent: ${t.accent}; --accent-hover: ${t.hover}; --accent-soft: ${t.soft}; --accent-ink: ${t.accentInk}; --on-accent: ${t.on};`;
let css = `/* Generated by scripts/palettes.mjs from content/accents.json. Do not edit. */\n`;
for (const p of accents.accents) {
  // :root[...] outranks the base tokens whatever the order of the sheets.
  css += `:root[data-palette="${p.id}"] { ${map(p.light)} }\n`;
  css += `:root[data-palette="${p.id}"][data-theme="dark"] { ${map(p.dark)} }\n`;
}
await writeFile(new URL("../src/styles/palettes.css", here), css);
const list = accents.accents.map((p) => ({ id: p.id, label: p.label, hint: p.hint, light: { paper: p.light.paper, accent: p.light.accent, ink: p.light.ink }, dark: { paper: p.dark.paper, accent: p.dark.accent, ink: p.dark.ink } }));
await writeFile(new URL("../src/data/palettes.js", here), `// Generated by scripts/palettes.mjs from content/accents.json. Do not edit.\nexport const DEFAULT_PALETTE = ${JSON.stringify(accents.default)};\nexport const PALETTES = ${JSON.stringify(list, null, 2)};\n`);
const htmlPath = new URL("../index.html", here);
let html = await readFile(htmlPath, "utf8");
html = html.replace(/(<style id="palettes">)[\s\S]*?(<\/style>)/, `$1\n${css.replace(/^\/\*.*\*\/\n/, "")}$2`);
await writeFile(htmlPath, html);
console.log(`palettes: ${accents.accents.length} written (default ${accents.default})`);
